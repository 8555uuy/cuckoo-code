const path = require('node:path');
const os = require('node:os');
const { spawn } = require('node:child_process');
const dir = path.join(os.homedir(), '.cuckoo', 'profiles', 'default');
const appRoot = 'C:/d/SourceCode/2026/cuckoo-code';
const nodeExe = path.join(appRoot, 'resources', 'runtime', 'win-x64', 'bin', 'node.exe');
const pnpmCjs = path.join(appRoot, 'resources', 'runtime', 'pnpm', 'bin', 'pnpm.cjs');
console.log('跑 pnpm install ...');
const child = spawn(nodeExe, [pnpmCjs, 'install'], { cwd: dir, env: Object.assign({}, process.env, { PNPM_HOME: '' }), stdio: 'inherit' });
child.on('close', (code) => { console.log('pnpm install 退出码: ' + code); process.exit(code == null ? 0 : code); });
